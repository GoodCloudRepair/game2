// Batch trim script for chapters 006, 014, 016, 019, 022, 034, 035, 042, 043
const fs = require('fs');
const path = require('path');
const base = 'e:/game2/小说/全球迷雾：我能校正万物词条/卷01_雾降临城/正文';

function countChars(text) {
  return text.replace(/[\r\n\s]/g, '').length;
}

function trimFile(filename, repls) {
  const filePath = path.join(base, filename);
  let text = fs.readFileSync(filePath, 'utf8');
  const before = countChars(text);
  let applied = 0;
  
  for (const [old, nu] of repls) {
    if (text.includes(old)) {
      text = text.replace(old, nu);
      applied++;
    }
  }
  
  fs.writeFileSync(filePath, text);
  const after = countChars(text);
  console.log(filename.substring(0, 6) + ': ' + before + ' \u2192 ' + after + ' (' + applied + '/' + repls.length + ' applied)');
  return after;
}

