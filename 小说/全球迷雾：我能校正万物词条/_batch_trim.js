// The unicode approach is too hard to read. Let me use a different strategy.
// I'll write the content directly.

function processChapter(filename, fn) {
  const filePath = path.join(base, filename);
  let text = fs.readFileSync(filePath, 'utf8');
  const before = countChars(text);
  text = fn(text);
  fs.writeFileSync(filePath, text);
  const after = countChars(text);
  console.log(filename.substring(0, 6) + ': ' + before + ' -> ' + after + ' (cut ' + (before - after) + ')');
}

